-- 0052: Hourly workload usage rollup for memory-bounded recommendation scans (E3, BUG-12).
-- One row per hour, workload target, container ('' = pod-level aggregate) and node.
-- Usage percentiles are taken over per-step values within the hour; scans read
-- one summary per target container computed in SQL over the lookback window.
CREATE TABLE IF NOT EXISTS workload_usage_hourly (
    hour_bucket TIMESTAMP WITH TIME ZONE NOT NULL,
    namespace TEXT NOT NULL,
    target_kind TEXT NOT NULL,
    target_name TEXT NOT NULL,
    container_name TEXT NOT NULL DEFAULT '',
    node TEXT NOT NULL DEFAULT '',
    hour_of_day SMALLINT NOT NULL,
    sample_count BIGINT NOT NULL DEFAULT 0,
    pod_count INTEGER NOT NULL DEFAULT 0,
    step_count BIGINT NOT NULL DEFAULT 0,
    duration_seconds DOUBLE PRECISION NOT NULL DEFAULT 0,
    cpu_sample_count BIGINT NOT NULL DEFAULT 0,
    cpu_usage_avg DOUBLE PRECISION,
    cpu_usage_sq_avg DOUBLE PRECISION,
    cpu_usage_p50 DOUBLE PRECISION,
    cpu_usage_p90 DOUBLE PRECISION,
    cpu_usage_p95 DOUBLE PRECISION,
    cpu_usage_p99 DOUBLE PRECISION,
    cpu_usage_max DOUBLE PRECISION,
    memory_sample_count BIGINT NOT NULL DEFAULT 0,
    memory_usage_avg DOUBLE PRECISION,
    memory_usage_p50 DOUBLE PRECISION,
    memory_usage_p90 DOUBLE PRECISION,
    memory_usage_p95 DOUBLE PRECISION,
    memory_usage_p99 DOUBLE PRECISION,
    memory_usage_max DOUBLE PRECISION,
    cpu_request BIGINT NOT NULL DEFAULT 0,
    memory_request BIGINT NOT NULL DEFAULT 0,
    cpu_request_sum DOUBLE PRECISION NOT NULL DEFAULT 0,
    memory_request_sum DOUBLE PRECISION NOT NULL DEFAULT 0,
    cpu_limit BIGINT,
    memory_limit BIGINT,
    restart_count INTEGER,
    total_cost DOUBLE PRECISION NOT NULL DEFAULT 0,
    cost_cpu DOUBLE PRECISION,
    cost_ram DOUBLE PRECISION,
    cost_storage DOUBLE PRECISION,
    cost_network DOUBLE PRECISION,
    cost_lb DOUBLE PRECISION,
    cost_source TEXT,
    co2e_grams DOUBLE PRECISION NOT NULL DEFAULT 0,
    embodied_co2e_grams DOUBLE PRECISION NOT NULL DEFAULT 0,
    joules DOUBLE PRECISION NOT NULL DEFAULT 0,
    pue DOUBLE PRECISION,
    grid_intensity DOUBLE PRECISION,
    intensity_sample_count BIGINT NOT NULL DEFAULT 0,
    emaps_zone TEXT,
    node_instance_type TEXT,
    source TEXT NOT NULL DEFAULT 'raw',
    PRIMARY KEY (hour_bucket, namespace, target_kind, target_name, container_name, node)
);
CREATE INDEX IF NOT EXISTS idx_workload_usage_hourly_ns_bucket
    ON workload_usage_hourly(namespace, hour_bucket);
