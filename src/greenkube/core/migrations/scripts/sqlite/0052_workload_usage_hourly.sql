-- 0052: Hourly workload usage rollup for memory-bounded recommendation scans (E3, BUG-12).
-- One row per hour, workload target, container ('' = pod-level aggregate) and node.
-- Usage percentiles are taken over per-step values within the hour; scans read
-- one summary per target container computed in SQL over the lookback window.
CREATE TABLE IF NOT EXISTS workload_usage_hourly (
    hour_bucket TEXT NOT NULL,
    namespace TEXT NOT NULL,
    target_kind TEXT NOT NULL,
    target_name TEXT NOT NULL,
    container_name TEXT NOT NULL DEFAULT '',
    node TEXT NOT NULL DEFAULT '',
    hour_of_day INTEGER NOT NULL,
    sample_count INTEGER NOT NULL DEFAULT 0,
    pod_count INTEGER NOT NULL DEFAULT 0,
    step_count INTEGER NOT NULL DEFAULT 0,
    duration_seconds REAL NOT NULL DEFAULT 0,
    cpu_sample_count INTEGER NOT NULL DEFAULT 0,
    cpu_usage_avg REAL,
    cpu_usage_sq_avg REAL,
    cpu_usage_p50 REAL,
    cpu_usage_p90 REAL,
    cpu_usage_p95 REAL,
    cpu_usage_p99 REAL,
    cpu_usage_max REAL,
    memory_sample_count INTEGER NOT NULL DEFAULT 0,
    memory_usage_avg REAL,
    memory_usage_p50 REAL,
    memory_usage_p90 REAL,
    memory_usage_p95 REAL,
    memory_usage_p99 REAL,
    memory_usage_max REAL,
    cpu_request INTEGER NOT NULL DEFAULT 0,
    memory_request INTEGER NOT NULL DEFAULT 0,
    cpu_request_sum REAL NOT NULL DEFAULT 0,
    memory_request_sum REAL NOT NULL DEFAULT 0,
    cpu_limit INTEGER,
    memory_limit INTEGER,
    restart_count INTEGER,
    total_cost REAL NOT NULL DEFAULT 0,
    cost_cpu REAL,
    cost_ram REAL,
    cost_storage REAL,
    cost_network REAL,
    cost_lb REAL,
    cost_source TEXT,
    co2e_grams REAL NOT NULL DEFAULT 0,
    embodied_co2e_grams REAL NOT NULL DEFAULT 0,
    joules REAL NOT NULL DEFAULT 0,
    pue REAL,
    grid_intensity REAL,
    intensity_sample_count INTEGER NOT NULL DEFAULT 0,
    emaps_zone TEXT,
    node_instance_type TEXT,
    source TEXT NOT NULL DEFAULT 'raw',
    PRIMARY KEY (hour_bucket, namespace, target_kind, target_name, container_name, node)
);
CREATE INDEX IF NOT EXISTS idx_workload_usage_hourly_ns_bucket
    ON workload_usage_hourly(namespace, hour_bucket);
