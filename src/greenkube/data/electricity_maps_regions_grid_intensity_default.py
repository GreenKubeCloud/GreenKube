# src/greenkube/data/electricity_maps_regions_grid_intensity_default.py
"""Bundled annual grid carbon intensity per Electricity Maps zone (NRG-04).

``electricity_maps_default.csv`` holds one row per Electricity Maps zone with the annual mean
intensity of its country for one calendar year (``year``), from Ember's yearly electricity data
(life-cycle emission factors, gCO2e/kWh), regenerated by ``scripts/generate_zone_intensity_defaults.py``.
Sub-zones (``US-CAL-CISO``, ``SE-SE3``) carry no value of their own and resolve to their country.

These values are used only when no live or stored intensity is available (no provider token,
or a provider outage longer than ``INTENSITY_MAX_AGE``). Create an Electricity Maps or Wattnet
token for hourly values.
"""

from __future__ import annotations

import csv
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Optional

from pydantic import BaseModel, Field, ValidationError, field_validator

logger = logging.getLogger(__name__)

CSV_PATH = Path(__file__).parent / "electricity_maps_default.csv"
CSV_COLUMNS = ("zone", "country", "name", "intensity_g_per_kwh", "year", "source", "emission_factor_type")

#: ``ZoneDefault.level`` values, also stored as ``intensity_source``.
LEVEL_ZONE = "zone_default"
LEVEL_COUNTRY = "country_default"


class ZoneDefaultRow(BaseModel):
    """One validated row of the bundled table."""

    zone: str = Field(min_length=2)
    country: str
    name: str
    intensity_g_per_kwh: Optional[float] = Field(None, ge=5, le=1500)
    year: Optional[int] = Field(None, ge=2015, le=2100)
    source: Optional[str] = None
    emission_factor_type: Optional[str] = None

    @field_validator("intensity_g_per_kwh", "year", "source", "emission_factor_type", mode="before")
    @classmethod
    def _blank_is_none(cls, value):
        return None if isinstance(value, str) and not value.strip() else value


@dataclass(frozen=True)
class ZoneDefault:
    """A bundled intensity and the level it was found at (``zone_default`` or ``country_default``)."""

    value: float
    level: str
    zone: str
    year: Optional[int]


def load_rows(path: Path = CSV_PATH) -> list[ZoneDefaultRow]:
    """Parses and validates the table; raises ``ValueError`` on a malformed row or header."""
    with open(path, newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        if tuple(reader.fieldnames or ()) != CSV_COLUMNS:
            raise ValueError(f"{path.name}: expected columns {CSV_COLUMNS}, got {reader.fieldnames}")
        rows = []
        for line, raw in enumerate(reader, start=2):
            if None in raw or any(value is None for value in raw.values()):
                raise ValueError(f"{path.name}:{line}: wrong number of columns")
            try:
                rows.append(ZoneDefaultRow.model_validate(raw))
            except ValidationError as error:
                raise ValueError(f"{path.name}:{line}: {error}") from error
    return rows


def _load() -> tuple[Dict[str, float], Dict[str, Optional[int]]]:
    try:
        rows = load_rows()
    except (OSError, ValueError) as error:
        logger.error("Failed to load the bundled zone intensity defaults: %s", error)
        return {}, {}
    values = {row.zone: row.intensity_g_per_kwh for row in rows if row.intensity_g_per_kwh is not None}
    years = {row.zone: row.year for row in rows if row.intensity_g_per_kwh is not None}
    return values, years


DEFAULT_GRID_INTENSITY_BY_ZONE, _YEARS = _load()
#: Calendar year of the bundled values (exposed as ``intensity_defaults_year``).
DEFAULT_INTENSITY_YEAR: Optional[int] = max((y for y in _YEARS.values() if y), default=None)


def parent_zone(zone: str) -> Optional[str]:
    """Country zone of a sub-zone (``US-CAL-CISO`` -> ``US``, ``SE-SE3`` -> ``SE``), else ``None``."""
    head, sep, _ = zone.partition("-")
    return head if sep and head else None


def resolve_default_intensity(zone: Optional[str]) -> Optional[ZoneDefault]:
    """The bundled intensity of ``zone``: its own value, else its country's, else ``None``."""
    if not zone:
        return None
    value = DEFAULT_GRID_INTENSITY_BY_ZONE.get(zone)
    if value is not None:
        return ZoneDefault(value=value, level=LEVEL_ZONE, zone=zone, year=_YEARS.get(zone))
    parent = parent_zone(zone)
    if parent is not None and parent in DEFAULT_GRID_INTENSITY_BY_ZONE:
        return ZoneDefault(
            value=DEFAULT_GRID_INTENSITY_BY_ZONE[parent], level=LEVEL_COUNTRY, zone=parent, year=_YEARS.get(parent)
        )
    return None
